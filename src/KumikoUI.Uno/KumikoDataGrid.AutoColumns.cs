using KumikoUI.Core.Models;
using Microsoft.UI.Xaml;

namespace KumikoUI.Uno;

/// <summary>Columns generated from the properties of the items (#315).</summary>
public partial class KumikoDataGrid
{
    private readonly KumikoColumnAutoGenerator _autoColumns = new();
    private bool _updatingAutoColumns;

    /// <summary>Identifies the <see cref="AutoGenerateColumns"/> dependency property.</summary>
    public static readonly DependencyProperty AutoGenerateColumnsProperty = DependencyProperty.Register(
        nameof(AutoGenerateColumns), typeof(KumikoAutoGenerateColumnsMode), typeof(KumikoDataGrid),
        new PropertyMetadata(KumikoAutoGenerateColumnsMode.None, (d, _) => ((KumikoDataGrid)d).UpdateAutoGeneratedColumns()));

    /// <summary>
    /// Whether the grid builds columns from the properties of its items. Default
    /// <see cref="KumikoAutoGenerateColumnsMode.None"/>: only declared <see cref="Columns"/> are shown. With
    /// <see cref="KumikoAutoGenerateColumnsMode.Auto"/> columns are generated when none is declared; with
    /// <see cref="KumikoAutoGenerateColumnsMode.Merge"/> they are generated for the properties no declared column binds.
    /// Generated columns are added to <see cref="Columns"/> (with <see cref="KumikoColumn.IsAutoGenerated"/> set) when the
    /// first item is known, and replaced when <see cref="ItemsSource"/> holds items of another type. See
    /// <see cref="KumikoColumnFactory"/> for how a property maps to a column.
    /// </summary>
    public KumikoAutoGenerateColumnsMode AutoGenerateColumns
    {
        get => (KumikoAutoGenerateColumnsMode)GetValue(AutoGenerateColumnsProperty);
        set => SetValue(AutoGenerateColumnsProperty, value);
    }

    /// <summary>
    /// Raised for each column the grid is about to generate (<see cref="AutoGenerateColumns"/>), before it is added to
    /// <see cref="Columns"/>: change the column, replace it, or cancel it.
    /// </summary>
    public event EventHandler<KumikoAutoGeneratingColumnEventArgs>? AutoGeneratingColumn;

    /// <summary>
    /// Raised once after the grid generated columns (<see cref="AutoGenerateColumns"/>) and added them to
    /// <see cref="Columns"/>, for example to restore a saved layout that includes generated columns.
    /// </summary>
    public event EventHandler? AutoGeneratedColumns;

    /// <summary>Adds, replaces or removes the generated columns to match the items and the mode.</summary>
    private void UpdateAutoGeneratedColumns()
    {
        if (_updatingAutoColumns) return;
        // Columns is null only while the constructor sets the defaults
        if (GetValue(ColumnsProperty) is not System.Collections.ObjectModel.ObservableCollection<KumikoColumn> columns) return;

        KumikoColumnAutoGenerator.Result result;
        _updatingAutoColumns = true;
        try
        {
            result = _autoColumns.Update(columns, ItemsSource, AutoGenerateColumns,
                AutoGeneratingColumn is null ? null : args => AutoGeneratingColumn?.Invoke(this, args));
        }
        finally
        {
            _updatingAutoColumns = false;
        }

        if (result.Changed)
        {
            _dataSource.SetColumns(columns);
            SyncActionButtonDefinitions();
            Invalidate();
        }

        if (result.Generated)
            AutoGeneratedColumns?.Invoke(this, EventArgs.Empty);
    }

    /// <summary>The items were empty when columns were due: generate once the first item arrives.</summary>
    private void UpdateAutoGeneratedColumnsIfWaiting()
    {
        if (!_autoColumns.IsWaitingForItems) return;
        if (DispatcherQueue is { } queue && !queue.HasThreadAccess)
            queue.TryEnqueue(UpdateAutoGeneratedColumns);
        else
            UpdateAutoGeneratedColumns();
    }
}
