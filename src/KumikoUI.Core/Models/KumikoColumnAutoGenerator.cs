using System.Collections;

namespace KumikoUI.Core.Models;

/// <summary>
/// The host-independent part of <c>AutoGenerateColumns</c>: decides when the generated columns of a grid's
/// <c>Columns</c> collection are added, replaced or removed. Each host owns one and calls <see cref="Update"/> when its
/// items, its columns collection or the mode change, and while <see cref="IsWaitingForItems"/> when items are added.
/// </summary>
internal sealed class KumikoColumnAutoGenerator
{
    private Type? _itemType;
    private KumikoAutoGenerateColumnsMode _mode;

    /// <summary>The outcome of <see cref="Update"/>.</summary>
    /// <param name="Changed">The columns collection was changed.</param>
    /// <param name="Generated">A generation pass ran (raise the host's <c>AutoGeneratedColumns</c>).</param>
    internal readonly record struct Result(bool Changed, bool Generated);

    /// <summary>
    /// True when generation is on but the items had no non-null item to take the type from; call <see cref="Update"/>
    /// again when items are added.
    /// </summary>
    public bool IsWaitingForItems { get; private set; }

    /// <summary>Forgets what was generated, so the next <see cref="Update"/> generates again (a new columns collection).</summary>
    public void Reset() => _itemType = null;

    /// <summary>
    /// Brings the generated columns of <paramref name="columns"/> in line with <paramref name="items"/> and
    /// <paramref name="mode"/>. Generated columns are built first and the collection is changed only after every
    /// <paramref name="generating"/> callback returned, so a throwing handler leaves the columns as they were.
    /// </summary>
    public Result Update(
        IList<KumikoColumn> columns,
        IEnumerable? items,
        KumikoAutoGenerateColumnsMode mode,
        Action<KumikoAutoGeneratingColumnEventArgs>? generating)
    {
        IsWaitingForItems = false;

        if (mode == KumikoAutoGenerateColumnsMode.None)
        {
            _itemType = null;
            _mode = mode;
            return new Result(RemoveGenerated(columns), false);
        }

        var itemType = FirstItemType(items);
        if (itemType == null)
        {
            // Keep what is there (a refill with the same type should not flash the columns away) and wait.
            IsWaitingForItems = true;
            return default;
        }

        if (itemType == _itemType && mode == _mode)
            return default;

        var declared = columns.Where(c => !c.IsAutoGenerated).ToList();

        var generated = new List<KumikoColumn>();
        bool generates = mode == KumikoAutoGenerateColumnsMode.Merge || declared.Count == 0; // Auto yields to declared columns
        if (generates)
        {
            HashSet<string>? bound = null;
            if (mode == KumikoAutoGenerateColumnsMode.Merge)
            {
                bound = new HashSet<string>(
                    declared.Where(c => !string.IsNullOrEmpty(c.PropertyName)).Select(c => c.PropertyName),
                    StringComparer.OrdinalIgnoreCase);
            }

            var unbound = KumikoColumnFactory.GetGeneratedMetadata(itemType)
                .Where(m => bound == null || !bound.Contains(m.PropertyName));
            foreach (var metadata in unbound)
            {
                if (KumikoColumnFactory.Create(metadata) is not { } column) continue;

                if (generating != null)
                {
                    var args = new KumikoAutoGeneratingColumnEventArgs(metadata, column);
                    generating(args);
                    if (args.Cancel) continue;
                    column = args.Column;
                }

                column.IsAutoGenerated = true;
                generated.Add(column);
            }
        }

        bool changed = RemoveGenerated(columns);
        foreach (var column in generated)
            columns.Add(column);

        _itemType = itemType;
        _mode = mode;
        return new Result(changed || generated.Count > 0, generates);
    }

    private static bool RemoveGenerated(IList<KumikoColumn> columns)
    {
        bool removed = false;
        for (int i = columns.Count - 1; i >= 0; i--)
        {
            if (columns[i].IsAutoGenerated)
            {
                columns.RemoveAt(i);
                removed = true;
            }
        }
        return removed;
    }

    /// <summary>The run-time type of the first non-null item, or null.</summary>
    internal static Type? FirstItemType(IEnumerable? items)
    {
        switch (items)
        {
            case null:
                return null;
            case IList list:
                for (int i = 0; i < list.Count; i++)
                {
                    if (list[i] is { } item)
                        return item.GetType();
                }
                return null;
            default:
                foreach (object? item in items)
                {
                    if (item != null)
                        return item.GetType();
                }
                return null;
        }
    }
}
