public class AutoGeneratedColumnsTests
{
    private static readonly string[] ExpectedOrder =
    {
        "First", "OrderDate", // [Display(Order)] first, by order
        "Id", "Label", "Customer", "Total", "Quantity", "Shipped", "Paid", "Status", "PreviousStatus", "Due",
        "Duration", "Reference", "Locked", "Frozen", "Computed", "InitOnly",
    };

    public static TheoryData<Type> OrderTypes => new() { typeof(GenAutoOrder), typeof(RefAutoOrder) };

    // ── Metadata and the factory ─────────────────────────────────

    [Fact]
    public void GeneratedAndReflectedMetadata_DescribeTheSameProperties()
    {
        var generated = KumikoColumnMetadataRegistry.GetColumns(typeof(GenAutoOrder));
        var reflected = KumikoColumnMetadataRegistry.GetColumns(typeof(RefAutoOrder));

        Assert.Equal(reflected.Select(Describe), generated.Select(Describe));

        static string Describe(KumikoColumnMetadata m) =>
            $"{m.PropertyName}|{m.PropertyType}|{m.DisplayName}|{m.ShortName}|{m.Description}|{m.Order}|{m.Format}|" +
            $"{m.IsReadOnly}|{m.AutoGenerate}|{(m.EnumValues == null ? "" : string.Join(",", m.EnumValues))}";
    }

    [Fact]
    public void GeneratedMetadata_ListsBasePropertiesFirst_InDeclarationOrder()
    {
        var names = KumikoColumnMetadataRegistry.GetColumns(typeof(GenAutoOrder)).Select(m => m.PropertyName).ToList();

        Assert.Equal(new[] { "Id", "Label", "Customer", "OrderDate" }, names.Take(4));
        Assert.Contains("Hidden", names); // listed, but not generated
    }

    [Theory]
    [MemberData(nameof(OrderTypes))]
    public void FromType_OrdersColumns_ByDisplayOrderThenDeclaration_AndSkipsHiddenAndUnsupported(Type type)
    {
        var columns = KumikoColumnFactory.FromType(type);

        Assert.Equal(ExpectedOrder, columns.Select(c => c.PropertyName));
    }

    [Theory]
    [MemberData(nameof(OrderTypes))]
    public void FromType_MapsPropertyTypesToColumnTypes(Type type)
    {
        var columns = KumikoColumnFactory.FromType(type).ToDictionary(c => c.PropertyName);

        Assert.Equal(KumikoColumnType.Text, columns["Customer"].ColumnType);
        Assert.Equal(KumikoColumnType.DateTime, columns["OrderDate"].ColumnType);
        Assert.Equal(KumikoColumnType.Date, columns["Due"].ColumnType);
        Assert.Equal(KumikoColumnType.Numeric, columns["Total"].ColumnType);
        Assert.Equal(KumikoTextAlignment.Right, columns["Total"].TextAlignment);
        Assert.Equal(KumikoColumnType.Numeric, columns["Quantity"].ColumnType);
        Assert.Equal(KumikoColumnType.Boolean, columns["Shipped"].ColumnType);
        Assert.False(columns["Shipped"].IsThreeState);
        Assert.True(columns["Paid"].IsThreeState);
        Assert.Equal(KumikoColumnType.ComboBox, columns["Status"].ColumnType);
        Assert.Equal(KumikoColumnType.ComboBox, columns["PreviousStatus"].ColumnType);
        Assert.Equal(KumikoColumnType.Time, columns["Duration"].ColumnType);
        Assert.Equal(KumikoColumnType.Text, columns["Reference"].ColumnType);
    }

    [Theory]
    [MemberData(nameof(OrderTypes))]
    public void FromType_EnumColumns_OfferEveryValueOnce(Type type)
    {
        var status = KumikoColumnFactory.FromType(type).Single(c => c.PropertyName == "Status");

        Assert.Equal(new object[] { AutoStatus.Open, AutoStatus.Closed, AutoStatus.Archived }, status.EditorItems!.Cast<object>());
    }

    [Theory]
    [MemberData(nameof(OrderTypes))]
    public void FromType_UsesDisplayNamesAndFormats(Type type)
    {
        var columns = KumikoColumnFactory.FromType(type).ToDictionary(c => c.PropertyName);

        Assert.Equal("Date", columns["OrderDate"].Header);           // ShortName wins over Name
        Assert.Equal("From resources", columns["First"].Header);     // read from the resource type
        Assert.Equal("Customer", columns["Customer"].Header);        // no attribute: the property name
        Assert.Equal("C2", columns["Total"].Format);                 // "{0:C2}" unwrapped
        Assert.Null(columns["Customer"].Format);
    }

    [Theory]
    [MemberData(nameof(OrderTypes))]
    public void FromType_ReadOnlyColumns_FollowSettersAndAttributes(Type type)
    {
        var columns = KumikoColumnFactory.FromType(type).ToDictionary(c => c.PropertyName);

        Assert.False(columns["Customer"].IsReadOnly);
        Assert.True(columns["Locked"].IsReadOnly);   // [Editable(false)]
        Assert.True(columns["Frozen"].IsReadOnly);   // [ReadOnly(true)]
        Assert.True(columns["Computed"].IsReadOnly); // no setter
        Assert.True(columns["InitOnly"].IsReadOnly); // init-only
    }

    [Fact]
    public void FromType_ColumnsAreNotMarkedAsGenerated()
    {
        Assert.All(KumikoColumnFactory.FromType(typeof(GenAutoPerson)), c => Assert.False(c.IsAutoGenerated));
    }

    [Theory]
    [InlineData("{0:C2}", "C2")]
    [InlineData("C2", "C2")]
    [InlineData("{0,10:N0}", "N0")]
    [InlineData("{0:yyyy-MM-dd}", "yyyy-MM-dd")]
    [InlineData("{0}", null)]
    [InlineData("{0:C} USD", null)]
    [InlineData("Total: {0:C}", null)]
    [InlineData("", null)]
    [InlineData(null, null)]
    public void NormalizeFormat_UnwrapsASinglePlaceholder(string? format, string? expected)
    {
        Assert.Equal(expected, KumikoColumnFactory.NormalizeFormat(format));
    }

    [Fact]
    public void Create_ReturnsNull_ForTypesWithoutAColumn()
    {
        Assert.Null(KumikoColumnFactory.Create(new KumikoColumnMetadata("Tags", typeof(List<string>))));
        Assert.Null(KumikoColumnFactory.Create(new KumikoColumnMetadata("Blob", typeof(byte[]))));
        Assert.Null(KumikoColumnFactory.Create(new KumikoColumnMetadata("Parent", typeof(AutoBase))));
    }

    [Fact]
    public void RegisteredProvider_WinsOverReflection()
    {
        KumikoColumnMetadataRegistry.Register(typeof(ProviderItem), new ProviderItem.Provider());

        var columns = KumikoColumnFactory.FromType(typeof(ProviderItem));

        Assert.Equal("Custom", Assert.Single(columns).Header);
    }

    private sealed class ProviderItem
    {
        public string Name { get; set; } = "";
        public int Ignored { get; set; }

        public sealed class Provider : IKumikoColumnMetadataProvider
        {
            public IReadOnlyList<KumikoColumnMetadata> GetColumns(Type itemType) =>
                new[] { new KumikoColumnMetadata(nameof(Name), typeof(string)) { DisplayName = "Custom" } };
        }
    }

    // ── Generation rules (the hosts' AutoGenerateColumns) ────────

    private static List<GenAutoPerson> People() => new() { new() { Name = "Ann", Age = 30 } };

    [Fact]
    public void None_GeneratesNothing_AndRemovesGeneratedColumns()
    {
        var columns = new ObservableCollection<KumikoColumn>();
        var generator = new KumikoColumnAutoGenerator();
        generator.Update(columns, People(), KumikoAutoGenerateColumnsMode.Auto, null);
        Assert.Equal(2, columns.Count);

        var result = generator.Update(columns, People(), KumikoAutoGenerateColumnsMode.None, null);

        Assert.Empty(columns);
        Assert.True(result.Changed);
        Assert.False(result.Generated);
    }

    [Fact]
    public void Auto_GeneratesMarkedColumns_WhenNoneIsDeclared()
    {
        var columns = new ObservableCollection<KumikoColumn>();

        var result = new KumikoColumnAutoGenerator().Update(columns, People(), KumikoAutoGenerateColumnsMode.Auto, null);

        Assert.Equal(new[] { "Name", "Age" }, columns.Select(c => c.PropertyName));
        Assert.All(columns, c => Assert.True(c.IsAutoGenerated));
        Assert.True(result.Changed);
        Assert.True(result.Generated);
    }

    [Fact]
    public void Auto_YieldsToDeclaredColumns()
    {
        var declared = new KumikoColumn { Header = "Name", PropertyName = "Name" };
        var columns = new ObservableCollection<KumikoColumn> { declared };

        var result = new KumikoColumnAutoGenerator().Update(columns, People(), KumikoAutoGenerateColumnsMode.Auto, null);

        Assert.Same(declared, Assert.Single(columns));
        Assert.False(result.Changed);
        Assert.False(result.Generated);
    }

    [Fact]
    public void Merge_AppendsColumnsForUnboundProperties_AfterDeclaredOnes()
    {
        var declared = new KumikoColumn { Header = "Who", PropertyName = "name" }; // matched ignoring case
        var columns = new ObservableCollection<KumikoColumn> { declared };

        new KumikoColumnAutoGenerator().Update(columns, People(), KumikoAutoGenerateColumnsMode.Merge, null);

        Assert.Equal(new[] { "name", "Age" }, columns.Select(c => c.PropertyName));
        Assert.False(columns[0].IsAutoGenerated);
        Assert.True(columns[1].IsAutoGenerated);
    }

    [Fact]
    public void SameItemType_DoesNotRegenerate()
    {
        var columns = new ObservableCollection<KumikoColumn>();
        var generator = new KumikoColumnAutoGenerator();
        generator.Update(columns, People(), KumikoAutoGenerateColumnsMode.Auto, null);
        var first = columns.ToList();

        var result = generator.Update(columns, People(), KumikoAutoGenerateColumnsMode.Auto, null);

        Assert.Equal(first, columns);
        Assert.False(result.Changed);
        Assert.False(result.Generated);
    }

    [Fact]
    public void AnotherItemType_ReplacesGeneratedColumns_AndKeepsDeclaredOnes()
    {
        var declared = new KumikoColumn { Header = "Note", PropertyName = "Note" };
        var columns = new ObservableCollection<KumikoColumn> { declared };
        var generator = new KumikoColumnAutoGenerator();
        generator.Update(columns, People(), KumikoAutoGenerateColumnsMode.Merge, null);

        generator.Update(columns, new[] { new GenAutoProduct() }, KumikoAutoGenerateColumnsMode.Merge, null);

        Assert.Equal(new[] { "Note", "Sku", "Price" }, columns.Select(c => c.PropertyName));
        Assert.Same(declared, columns[0]);
    }

    [Fact]
    public void EmptyItems_WaitForTheFirstItem()
    {
        var items = new ObservableCollection<GenAutoPerson>();
        var columns = new ObservableCollection<KumikoColumn>();
        var generator = new KumikoColumnAutoGenerator();

        var result = generator.Update(columns, items, KumikoAutoGenerateColumnsMode.Auto, null);
        Assert.Empty(columns);
        Assert.False(result.Generated);
        Assert.True(generator.IsWaitingForItems);

        items.Add(new GenAutoPerson { Name = "Bo" });
        generator.Update(columns, items, KumikoAutoGenerateColumnsMode.Auto, null);

        Assert.Equal(2, columns.Count);
        Assert.False(generator.IsWaitingForItems);
    }

    [Fact]
    public void NullItems_AreSkipped_WhenFindingTheItemType()
    {
        Assert.Equal(typeof(GenAutoPerson), KumikoColumnAutoGenerator.FirstItemType(new object?[] { null, new GenAutoPerson() }));
        Assert.Equal(typeof(GenAutoPerson), KumikoColumnAutoGenerator.FirstItemType(Enumerate()));
        Assert.Null(KumikoColumnAutoGenerator.FirstItemType(new object?[] { null }));

        static IEnumerable<object?> Enumerate() { yield return null; yield return new GenAutoPerson(); }
    }

    [Fact]
    public void Callback_CanEditReplaceAndCancelColumns()
    {
        var columns = new ObservableCollection<KumikoColumn>();
        var replacement = new KumikoColumn { Header = "Years", PropertyName = "Age" };

        new KumikoColumnAutoGenerator().Update(columns, new[] { new GenAutoOrder() }, KumikoAutoGenerateColumnsMode.Auto, args =>
        {
            switch (args.Metadata.PropertyName)
            {
                case "Customer": args.Column.Width = 222; break;
                case "Total": args.Column = replacement; break;
                case "Id": args.Cancel = true; break;
            }
        });

        Assert.DoesNotContain(columns, c => c.PropertyName == "Id");
        Assert.Equal(222, columns.Single(c => c.PropertyName == "Customer").Width);
        Assert.Contains(replacement, columns);
        Assert.True(replacement.IsAutoGenerated);
    }

    [Fact]
    public void ThrowingCallback_LeavesTheColumnsAsTheyWere()
    {
        var declared = new KumikoColumn { Header = "Note", PropertyName = "Note" };
        var columns = new ObservableCollection<KumikoColumn> { declared };

        Assert.Throws<InvalidOperationException>(() =>
            new KumikoColumnAutoGenerator().Update(columns, People(), KumikoAutoGenerateColumnsMode.Merge,
                _ => throw new InvalidOperationException()));

        Assert.Same(declared, Assert.Single(columns));
    }

    [Fact]
    public void Reset_GeneratesAgainForTheSameType()
    {
        var generator = new KumikoColumnAutoGenerator();
        generator.Update(new ObservableCollection<KumikoColumn>(), People(), KumikoAutoGenerateColumnsMode.Auto, null);
        var fresh = new ObservableCollection<KumikoColumn>();

        generator.Reset();
        var result = generator.Update(fresh, People(), KumikoAutoGenerateColumnsMode.Auto, null);

        Assert.True(result.Generated);
        Assert.Equal(2, fresh.Count);
    }

    [Fact]
    public void GeneratedColumns_AreMatchedBySavedLayouts()
    {
        var columns = new ObservableCollection<KumikoColumn>();
        new KumikoColumnAutoGenerator().Update(columns, People(), KumikoAutoGenerateColumnsMode.Auto, null);
        var source = new KumikoSource();
        source.SetColumns(columns);
        source.SetItems(People());
        columns[1].Width = 77;
        string json = KumikoLayoutState.Capture(source).ToJson();

        var columns2 = new ObservableCollection<KumikoColumn>();
        new KumikoColumnAutoGenerator().Update(columns2, People(), KumikoAutoGenerateColumnsMode.Auto, null);
        var source2 = new KumikoSource();
        source2.SetColumns(columns2);
        source2.SetItems(People());
        KumikoLayoutState.FromJson(json).ApplyTo(source2);

        Assert.Equal(77, source2.Columns.Single(c => c.PropertyName == "Age").Width);
    }
}
