// Each model exists twice: once with [KumikoGridItem] (metadata from the source generator, as under Native AOT) and
// once without (metadata from reflection). The two paths must describe the same columns.

public enum AutoStatus { Open = 1, Closed = 2, Archived = 3, Done = 2 }

public static class AutoResources
{
    public static string OrderedHeader => "From resources";
}

