using System.Collections.ObjectModel;
using KumikoUI.Core.Models;

namespace KumikoUI.Maui.Tests;

/// <summary>The MAUI host's <see cref="KumikoDataGrid.AutoGenerateColumns"/> and its events (#315).</summary>
public class AutoGenerateColumnsTests
{
    public sealed class Person
    {
        public string Name { get; set; } = "";
        public int Age { get; set; }
    }

    public sealed class Product
    {
        public string Sku { get; set; } = "";
    }

    private static ObservableCollection<Person> People() => new() { new Person { Name = "Ann", Age = 30 } };

    [Fact]
    public void Default_IsNone_AndGeneratesNothing()
    {
        var grid = new KumikoDataGrid { ItemsSource = People() };

        Assert.Equal(KumikoAutoGenerateColumnsMode.None, grid.AutoGenerateColumns);
        Assert.Empty(grid.Columns);
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void Auto_GeneratesColumns_WhicheverPropertyIsSetFirst(bool modeFirst)
    {
        var grid = new KumikoDataGrid();
        if (modeFirst) grid.AutoGenerateColumns = KumikoAutoGenerateColumnsMode.Auto;
        grid.ItemsSource = People();
        if (!modeFirst) grid.AutoGenerateColumns = KumikoAutoGenerateColumnsMode.Auto;

        Assert.Equal(new[] { "Name", "Age" }, grid.Columns.Select(c => c.PropertyName));
        Assert.Equal(grid.Columns, grid.DataSource.Columns); // pushed to the data source
        Assert.Equal(30, grid.DataSource.GetCellValue(0, grid.Columns[1]));
    }

    [Fact]
    public void Events_RaiseOncePerColumn_ThenOnce()
    {
        var grid = new KumikoDataGrid();
        var generating = new List<string>();
        int generated = 0;
        grid.AutoGeneratingColumn += (_, e) =>
        {
            generating.Add(e.Metadata.PropertyName);
            if (e.Metadata.PropertyName == "Age") e.Cancel = true;
        };
        grid.AutoGeneratedColumns += (_, _) => generated++;

        grid.AutoGenerateColumns = KumikoAutoGenerateColumnsMode.Auto;
        grid.ItemsSource = People();
        grid.ItemsSource = People(); // same item type: nothing to do

        Assert.Equal(new[] { "Name", "Age" }, generating);
        Assert.Equal(1, generated);
        Assert.Equal("Name", Assert.Single(grid.Columns).PropertyName);
    }

    [Fact]
    public void EmptyCollection_GeneratesWhenTheFirstItemArrives()
    {
        var items = new ObservableCollection<Person>();
        var grid = new KumikoDataGrid { AutoGenerateColumns = KumikoAutoGenerateColumnsMode.Auto, ItemsSource = items };
        Assert.Empty(grid.Columns);

        items.Add(new Person { Name = "Bo" });

        Assert.Equal(2, grid.Columns.Count);
    }

    [Fact]
    public void NewItemType_ReplacesGeneratedColumns_AndKeepsDeclaredOnes()
    {
        var grid = new KumikoDataGrid { AutoGenerateColumns = KumikoAutoGenerateColumnsMode.Merge };
        var declared = new KumikoColumn { Header = "Note", PropertyName = "Note" };
        grid.Columns.Add(declared);
        grid.ItemsSource = People();

        grid.ItemsSource = new ObservableCollection<Product> { new() { Sku = "A-1" } };

        Assert.Equal(new[] { "Note", "Sku" }, grid.Columns.Select(c => c.PropertyName));
        Assert.Same(declared, grid.Columns[0]);
        Assert.Equal(grid.Columns, grid.DataSource.Columns);
    }

    [Fact]
    public void SwitchingToNone_RemovesGeneratedColumns()
    {
        var grid = new KumikoDataGrid { AutoGenerateColumns = KumikoAutoGenerateColumnsMode.Auto, ItemsSource = People() };

        grid.AutoGenerateColumns = KumikoAutoGenerateColumnsMode.None;

        Assert.Empty(grid.Columns);
        Assert.Empty(grid.DataSource.Columns);
    }

    [Fact]
    public void NewColumnsCollection_GetsGeneratedColumnsToo()
    {
        var grid = new KumikoDataGrid { AutoGenerateColumns = KumikoAutoGenerateColumnsMode.Merge, ItemsSource = People() };
        var declared = new KumikoColumn { Header = "Who", PropertyName = "Name" };

        grid.Columns = new ObservableCollection<KumikoColumn> { declared };

        Assert.Equal(new[] { "Name", "Age" }, grid.Columns.Select(c => c.PropertyName));
        Assert.Same(declared, grid.Columns[0]);
    }
}
